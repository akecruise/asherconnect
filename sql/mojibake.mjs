/**
 * ตรวจภาษาไทยเพี้ยนแบบ UTF-8 → cp874 (เซฟผ่าน PowerShell 5 / Windows Thai)
 *
 * ไทยหนึ่งตัวเป็น 3 ไบต์ E0 B8/B9 xx — พอถูกอ่านเป็น cp874 จะกลายเป็น
 * "เ" + "ธ"/"น" + อีกหนึ่งตัว ซ้ำกันเป็นแถว เช่น "[ลูกค้าเพิ่มเพื่อน]" → "[เธฅเธนเธ..."
 * ★ จับเฉพาะที่ซ้ำติดกัน 3 ชุดขึ้นไป — "เธอ" ตัวเดียวเป็นภาษาไทยจริง ห้ามจับ
 *   (เคยเกิดจริง: sql/202609211200_messenger_identity_p0.sql → แจ้งเตือนเพี้ยน 2026-10-01)
 */
export const MOJIBAKE = /(?:เ[ธน]\S){3,}/u

/** คืนเลขบรรทัด (เริ่ม 1) ที่เพี้ยน */
export const mojibakeLines = (text) =>
  text.split('\n').flatMap((l, i) => (MOJIBAKE.test(l) ? [i + 1] : []))
