-- ★★ ไฟล์นี้ตั้งใจ "ไม่แตะ" cron ของระบบเก่า (asher-report-daily /
--    asher-daily-report / asher-watchdog ที่ sql/011_cloud_functions.sql:146-151)
--    ระบบเก่ากับระบบใหม่ต้องเดินขนานกันก่อน แล้วค่อยเทียบตัวเลขว่าต่างกันตรงไหน
--    เพราะนิยามไม่เหมือนกัน (เก่า: นาฬิกาแขวนผนัง + ไม่แยก page ออกจาก unknown
--    ใหม่: หัก 00:00–06:00 + แยก responder_src) ตัวเลขจะไม่ตรงกันโดยธรรมชาติ
--    ★ การปิดของเก่าเป็นการตัดสินใจแยก ไม่ใช่ผลข้างเคียงของไฟล์นี้
--
-- ลบทิ้งเมื่อ cutover:
--   select cron.unschedule('asher-report-daily');
-- =====================================================================

create extension if not exists pg_cron;

-- ★ unschedule ก่อนเสมอ ไฟล์นี้จึงรันซ้ำได้โดยไม่เกิดงานซ้อน
--   (รูปแบบเดียวกับ sql/011:143-144)
select cron.unschedule(jobid) from cron.job
 where jobname in ('stats-mark-overdue','stats-rollup-daily','stats-abandon');

-- ทุก 5 นาที: รอบที่ยังไม่มีใครตอบและเกิน breach_sec แล้ว ให้ขึ้นสถานะ breach
-- ★ ความถี่นี้คือเหตุผลที่ stats_overview.overdue_now ตามหลังความจริงได้ไม่เกิน 5 นาที
--   ถ้าเปลี่ยนตรงนี้ ต้องไปแก้คอมเมนต์ใน sql/027 ด้วย ไม่งั้นจะอ่านแล้วเข้าใจผิด
select cron.schedule('stats-mark-overdue', '*/5 * * * *',
  $cron$select inbox.mark_overdue_windows()$cron$);

-- 00:15 เวลาไทย (17:15 UTC): รวมยอดของเมื่อวานลง agent_daily_stat
-- ★ ต้องหลังเที่ยงคืนไทยพอสมควร เพราะรอบที่เปิดคาบเกี่ยวเที่ยงคืนยังปิดไม่เสร็จ
select cron.schedule('stats-rollup-daily', '15 17 * * *',
  $cron$select inbox.rollup_agent_daily((now() at time zone 'Asia/Bangkok')::date - 1)$cron$);

-- 01:00 เวลาไทย (18:00 UTC): ปิดรอบที่ค้างเกิน 7 วัน ถือว่าลูกค้าหายไปแล้ว
-- ★ ถ้าไม่มีตัวนี้ รอบที่ไม่มีใครตอบจะค้างเป็น open ตลอดกาล แล้วตัวหารของ
--   เปอร์เซ็นต์ทุกตัวจะเพี้ยนสะสมไปเรื่อย ๆ โดยไม่มีอะไรฟ้อง
select cron.schedule('stats-abandon', '0 18 * * *',
  $cron$select inbox.abandon_stale_windows(7)$cron$);

